"""Preserve original native layout while applying Artifact Tool-authored edits.

Only approved formula/value cells, their dropdown source, and native calc/name
metadata change. Print settings, styles, freeze panes and unrelated ZIP parts
are retained from the reviewed workbook, not regenerated by an exporter.
"""
import json,copy,hashlib
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile
ROOT=Path(__file__).resolve().parent
NS={'s':'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
Q=lambda n:'{'+NS['s']+'}'+n
work=ROOT/'verification-2026-11-01';authored=work/'authored';final=work/'final'
plan=json.loads((authored/'changes.json').read_text());records=[]
names=['READ ME','OVERVIEW','QUICK QUOTE','CLIENT QUOTE','JOB SCENARIOS','JOB LOG','SERVICES','SETTINGS']
for filename,folder in [('Cleaning_Pricing_Calculator.xlsx','customer'),('Cleaning_Pricing_Calculator_FICTIONAL_DEMO.xlsx','examples')]:
    source=ROOT/'print-review-copies'/filename;dest=final/folder/filename;dest.parent.mkdir(parents=True,exist_ok=True)
    src_hash=hashlib.sha256(source.read_bytes()).hexdigest();edited=[]
    with ZipFile(source) as z,ZipFile(authored/filename) as generated,ZipFile(dest,'w') as out:
        for info in z.infolist():
            data=z.read(info.filename)
            if info.filename=='xl/workbook.xml':
                tree=ET.fromstring(data);defined=tree.find('s:definedNames',NS)
                if defined is None:defined=ET.SubElement(tree,Q('definedNames'))
                assert not any(x.attrib.get('name')=='ServiceNames' for x in defined)
                ET.SubElement(defined,Q('definedName'),{'name':'ServiceNames'}).text="'SERVICES'!$A$9:$A$15"
                calc=tree.find('s:calcPr',NS)
                if calc is None:calc=ET.SubElement(tree,Q('calcPr'))
                calc.attrib.update(calcMode='auto',fullCalcOnLoad='1',forceFullCalc='1')
                data=ET.tostring(tree,encoding='utf-8',xml_declaration=True)
            elif info.filename.startswith('xl/worksheets/sheet') and info.filename.endswith('.xml'):
                idx=int(info.filename.rsplit('sheet',1)[1].split('.')[0])-1;name=names[idx]
                if name in plan or name in ['QUICK QUOTE','JOB SCENARIOS']:
                    tree=ET.fromstring(data);new=ET.fromstring(generated.read(info.filename));cells={c.attrib['r']:c for c in tree.findall('.//s:sheetData/s:row/s:c',NS)};newcells={c.attrib['r']:c for c in new.findall('.//s:sheetData/s:row/s:c',NS)}
                    for address,edit in plan.get(name,{}).items():
                        cell=cells[address]
                        if 'formula' in edit:
                            old=cell.find('s:f',NS);replacement=newcells[address].find('s:f',NS)
                            assert replacement is not None and replacement.text==edit['formula'].lstrip('='),(name,address)
                            if old is not None:cell.remove(old)
                            cell.insert(0,copy.deepcopy(replacement))
                        else:
                            for child in list(cell):cell.remove(child)
                            cell.attrib['t']='str';ET.SubElement(cell,Q('v')).text=edit['value']
                        edited.append(name+'!'+address)
                    if name in ['QUICK QUOTE','JOB SCENARIOS']:
                        expected='B11' if name=='QUICK QUOTE' else 'B10:B34'
                        matches=[v for v in new.findall('s:dataValidations/s:dataValidation',NS) if v.attrib.get('sqref')==expected and v.findtext('s:formula1',namespaces=NS)=='ServiceNames']
                        assert matches,(name,'Artifact Tool did not author dropdown')
                        validation=next(v for v in tree.findall('s:dataValidations/s:dataValidation',NS) if v.attrib.get('sqref')==expected)
                        validation.find('s:formula1',NS).text='ServiceNames'
                    data=ET.tostring(tree,encoding='utf-8',xml_declaration=True)
            out.writestr(info,data)
    with ZipFile(source) as a,ZipFile(dest) as b:
        changed=[n for n in a.namelist() if a.read(n)!=b.read(n)]
        assert a.read('xl/styles.xml')==b.read('xl/styles.xml')
        assert a.read('xl/worksheets/sheet4.xml')==b.read('xl/worksheets/sheet4.xml')
        for i,name in enumerate(names,1):
            old=ET.fromstring(a.read(f'xl/worksheets/sheet{i}.xml'));new=ET.fromstring(b.read(f'xl/worksheets/sheet{i}.xml'))
            before={c.attrib['r']:ET.tostring(c) for c in old.findall('.//s:c',NS)};after={c.attrib['r']:ET.tostring(c) for c in new.findall('.//s:c',NS)}
            assert before.keys()==after.keys()
            assert all(before[c]==after[c] for c in before if c not in plan.get(name,{})),name
        assert b.testzip() is None
    assert hashlib.sha256(source.read_bytes()).hexdigest()==src_hash
    records.append({'name':filename,'source_sha256':src_hash,'candidate_sha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'changed_members':changed,'edited_cells':edited,'styles_identical':True,'client_quote_print_settings_identical':True,'unrelated_cells_identical':True})
(work/'candidate-preservation.json').write_text(json.dumps(records,indent=2),encoding='utf-8');print(json.dumps([{k:v for k,v in x.items() if k!='edited_cells'} for x in records],indent=2))
